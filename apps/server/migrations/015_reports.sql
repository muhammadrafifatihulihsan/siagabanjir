CREATE TABLE reports (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  group_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  description VARCHAR(2000) NOT NULL,
  latitude DECIMAL(10, 7) NOT NULL,
  longitude DECIMAL(10, 7) NOT NULL,
  location_source VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  occurred_at DATETIME(3) NULL,
  accepted_at DATETIME(3) NOT NULL,
  applied_time DATETIME(3) NOT NULL,
  time_source VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  accept_seq BIGINT UNSIGNED NOT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  evidence_version INT UNSIGNED NOT NULL DEFAULT 1,
  result_version INT UNSIGNED NOT NULL DEFAULT 1,
  needs_review_since DATETIME(3) NULL,
  deleted_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  KEY reports_owner (owner_id, accepted_at),
  KEY reports_group (group_id),
  CONSTRAINT reports_owner_fk FOREIGN KEY (owner_id) REFERENCES accounts (id),
  CONSTRAINT reports_group_fk FOREIGN KEY (group_id) REFERENCES `groups` (id),
  CONSTRAINT reports_location_source CHECK (location_source IN ('GPS', 'MANUAL')),
  CONSTRAINT reports_time_source CHECK (time_source IN ('OCCURRED', 'ACCEPTED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
